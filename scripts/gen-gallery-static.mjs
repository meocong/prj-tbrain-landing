#!/usr/bin/env node
// Scans public/images/ and emits src/lib/admin/gallery-static.ts,
// a plain TS module with a typed array of static image references.
// Runs as a prebuild step so Gallery always reflects the filesystem.

import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, extname, basename } from "node:path";

const ROOT = process.cwd();
const IMG_DIR = join(ROOT, "public", "images");
const OUT = join(ROOT, "src", "lib", "admin", "gallery-static.ts");

const ALLOWED = new Set([".jpg", ".jpeg", ".png", ".webp", ".svg", ".gif"]);

function listFiles(dir, rel = "") {
  const out = [];
  let entries;
  try { entries = readdirSync(dir); } catch { return out; }
  for (const name of entries) {
    const full = join(dir, name);
    let stats;
    try { stats = statSync(full); } catch { continue; }
    if (stats.isDirectory()) {
      out.push(...listFiles(full, join(rel, name)));
    } else if (stats.isFile() && ALLOWED.has(extname(name).toLowerCase())) {
      out.push({
        path: `/images/${rel ? rel + "/" : ""}${name}`.replace(/\\/g, "/"),
        name: basename(name, extname(name)),
        ext: extname(name).slice(1).toLowerCase(),
        size_bytes: stats.size,
        mtime: stats.mtimeMs,
      });
    }
  }
  return out;
}

const files = listFiles(IMG_DIR).sort((a, b) => a.path.localeCompare(b.path));

const body = `// AUTO-GENERATED by scripts/gen-gallery-static.mjs — do not edit by hand.
// Re-run as part of \`pnpm build\` or \`pnpm dev\`.

export type StaticImage = {
  path: string;
  name: string;
  ext: string;
  size_bytes: number;
};

export const STATIC_IMAGES: StaticImage[] = ${JSON.stringify(
  files.map(({ mtime, ...rest }) => rest),
  null,
  2
)};
`;

writeFileSync(OUT, body, "utf8");
console.log(`[gallery] wrote ${files.length} images → ${OUT.replace(ROOT + "/", "")}`);
